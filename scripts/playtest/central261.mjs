// VIDA 26.1 — confere a central na produção: abrir o Menu, buscar "muay thai" e "Counter-Strike", abrir o caminho, ir à tela real.
import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
const URL = process.env.URL ?? 'http://localhost:4173/';
const b = await chromium.launch(); const p = await b.newPage(); const erros = [];
p.on('pageerror', e => erros.push(e.message));
await p.goto(URL);
await p.evaluate(s => { localStorage.clear(); localStorage.setItem('VIDA_NOVIDADES_VISTAS', '26.1'); localStorage.setItem('VIDA_GAME_SAVE_V1', s); }, readFileSync(`${process.env.SP}/vida-v26-jovem.json`, 'utf8'));
await p.goto(URL); await p.getByRole('button', { name: /Continuar a vida/ }).click(); await p.waitForTimeout(1200);
const ok = [];
await p.getByRole('button', { name: 'Menu' }).click();
const menu = p.getByRole('dialog', { name: 'Menu' });
await menu.getByRole('searchbox').fill('muay thai');
ok.push(['muay thai → lutas', await menu.locator('[data-trajeto-busca="lutas"]').count() === 1]);
await menu.getByRole('searchbox').fill('Counter-Strike');
ok.push(['Counter-Strike → caminho do CS', await menu.locator('[data-trajeto-busca="esports_cs"]').count() === 1]);
await menu.locator('[data-trajeto-busca="esports_cs"]').click();
await menu.locator('[data-trajeto="esports_cs"][open]').waitFor({ timeout: 10000 }).catch(() => {});
ok.push(['explorador abre o CS', await menu.locator('[data-trajeto="esports_cs"][open]').count() === 1]);
await menu.locator('[data-trajeto="esports_cs"] .g26-ir').click();
await p.waitForTimeout(800);
ok.push(['"ir" leva a Outros caminhos', await p.locator('.divisoes-caminhos__item--ativa', { hasText: 'Outros caminhos' }).count() === 1]);
await p.getByRole('button', { name: 'Menu' }).click();
await p.getByRole('dialog', { name: 'Menu' }).locator('[data-grupo="pessoas"]').click();
await p.getByRole('dialog', { name: 'Menu' }).locator('[data-intencao="namoro"]').click();
await p.waitForTimeout(600);
ok.push(['área Pessoas → namoro abre Pessoas', await p.getByRole('dialog', { name: 'Menu' }).count() === 0]);
ok.push(['sem erro de página', erros.length === 0]);
for (const [n, x] of ok) console.log(x ? 'OK  ' : 'FALHA', n);
await b.close();
